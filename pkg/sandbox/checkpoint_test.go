func TestCheckpointDisksMergeContiguousPrefixAndPreserveEROFS(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	sink := snapshot.NewFileSink(dir, "sid", nil, false, nil)
	size := int64(4 * 4096)
	writeLayer := func(value byte, page int) string {
		body := bytes.Repeat([]byte{value}, int(size))
		holes := []sparse.Extent{}
		if page > 0 {
			holes = append(holes, sparse.Extent{Offset: 0, Size: uint64(page * 4096)})
		}
		if page < 3 {
			holes = append(holes, sparse.Extent{Offset: uint64((page + 1) * 4096), Size: uint64((3 - page) * 4096)})
		}
		ref, _, err := sink.AbsorbOverlay(ctx, bytes.NewReader(body), holes)
		if err != nil {
			t.Fatal(err)
		}
		return ref
	}
	old := writeLayer(1, 0)
	middle := writeLayer(2, 1)
	top := writeLayer(0, 0) // opaque zero replaces old data
	external := "manifest://" + strings.Repeat("e", 64)
	c0 := snapshotTestLivePortable(t)
	c0.Boot.Root.BaseFromRefs = []string{middle, old, external}
	opts := RunOptions{checkpointDir: dir, Cfg: &config.SandboxConfig{}, PortableConfig: c0,
		SourceBinding: &RunSourceBinding{SandboxRef: top, RuntimeRef: top, RelativeDir: dir}}
	views := 0
	disk := SnapDiskRef{Size: size, SnapshotView: func() (io.ReadSeeker, []sparse.Extent, error) {
		views++
		return bytes.NewReader(make([]byte, size)), nil, nil
	}}
	prepared, diffs, merged, open, err := prepareCheckpointDisks(ctx, opts, []SnapDiskRef{disk})
	if err != nil {
		t.Fatal(err)
	}
	if views != 0 {
		t.Fatal("preflight read guest writable state")
	}
	if !merged[0] || !reflect.DeepEqual(prepared.PortableConfig.Boot.Root.BaseFromRefs, []string{external}) {
		t.Fatalf("disk prefix did not converge: %v %+v", merged, prepared.PortableConfig.Boot.Root)
	}
	stream, err := open(ctx, diffs[0].MergeBase)
	if err != nil {
		t.Fatal(err)
	}
	defer stream.Close()
	got := make([]byte, size)
	if _, err := stream.ReadAt(ctx, got, 0); err != nil {
		t.Fatal(err)
	}
	want := make([]byte, size)
	copy(want[4096:8192], bytes.Repeat([]byte{2}, 4096))
	if !bytes.Equal(got, want) {
		t.Fatal("disk Data/Hole/Zero overlay differs")
	}
	run, err := stream.RunAt(8192, 4096)
	if err != nil || run.Kind() != sparse.Hole {
		t.Fatalf("disk lower fallthrough lost: %v %v", run, err)
	}
	if !reflect.DeepEqual(c0.Boot.Root.BaseFromRefs, []string{middle, old, external}) {
		t.Fatal("immutable C0 mutated")
	}
	// A direct EROFS self is not the ext4 upper's same-device parent.
	opts.PortableConfig = snapshotTestPortable(t)
	opts.PortableConfig.Boot.Root = config.PortableRootConfig{Base: "self", Overlay: &config.PortableOverlayConfig{}}
	prepared, diffs, merged, _, err = prepareCheckpointDisks(ctx, opts, []SnapDiskRef{disk})
	if err != nil || merged[0] || diffs[0].MergeBase != "" {
		t.Fatalf("EROFS merged into upper: %v %v", merged, err)
	}
	if prepared.PortableConfig.Boot.Root.Base != "self" || prepared.PortableConfig.Boot.Root.Overlay == nil {
		t.Fatal("immutable base separation changed")
	}
	// Same-path located template source remains an external owner.
	located, _ := manifest.ParseRef(top)
	located.Location = "template"
	opts.PortableConfig = c0
	opts.RefLocations = config.RefLocations{"template": dir}
	opts.SourceBinding.SandboxRef = located.String()
	_, _, merged, _, err = prepareCheckpointDisks(ctx, opts, []SnapDiskRef{disk})
	if err != nil || merged[0] {
		t.Fatalf("located disk parent absorbed: %v %v", merged, err)
	}
}
